// Turns tokens/tokens.json (W3C DTCG) into CSS custom properties.
// Output: src/styles/tokens.css, one `--dc-<path>` variable per token.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tree = JSON.parse(await readFile(path.join(root, "tokens/tokens.json"), "utf8"));
const PREFIX = "dc";

const leaves = [];
function walk(node, trail) {
  if (node && typeof node === "object" && "$value" in node) {
    leaves.push({ path: trail.join("."), token: node });
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    walk(child, [...trail, key]);
  }
}
walk(tree, []);

const byPath = new Map(leaves.map((l) => [l.path, l.token]));
const varName = (p) => `--${PREFIX}-${p.replace(/\./g, "-")}`;

function format(value) {
  if (Array.isArray(value)) return value.map((v) => (/\s/.test(v) ? `"${v}"` : v)).join(", ");
  if (typeof value === "string") {
    const ref = value.match(/^\{(.+)\}$/);
    if (ref) {
      if (!byPath.has(ref[1])) throw new Error(`Unknown token reference ${value}`);
      return `var(${varName(ref[1])})`;
    }
  }
  return String(value);
}

const lines = leaves.map((l) => `  ${varName(l.path)}: ${format(l.token.$value)};`);
const css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;

await mkdir(path.join(root, "src/styles"), { recursive: true });
await writeFile(path.join(root, "src/styles/tokens.css"), css);
console.log(`Wrote ${leaves.length} tokens to src/styles/tokens.css`);
